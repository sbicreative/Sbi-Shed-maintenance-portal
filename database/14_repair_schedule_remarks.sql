-- REVIEW BEFORE APPLYING. This migration has not been run against Supabase.
-- Central, append-only timeline for new repair schedule remarks.
-- Existing tables and historical remarks are not copied or modified.

BEGIN;

CREATE TABLE IF NOT EXISTS repair_schedule_remarks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    remark_text TEXT NOT NULL CHECK (btrim(remark_text) <> ''),
    author_id BIGINT,
    author_name VARCHAR(150) NOT NULL,
    author_role VARCHAR(30) NOT NULL,
    assignment_date DATE,
    loco_id BIGINT REFERENCES loco_master(id) ON DELETE RESTRICT,
    temporary_loco_id BIGINT REFERENCES temporary_loco_master(id) ON DELETE RESTRICT,
    assign_work_header_id BIGINT REFERENCES assign_work_header(id) ON DELETE RESTRICT,
    schedule_id BIGINT REFERENCES schedule_master(id) ON DELETE RESTRICT,
    assign_work_detail_id BIGINT REFERENCES assign_work_details(id) ON DELETE RESTRICT,
    manpower_distribution_id BIGINT REFERENCES manpower_distribution(id) ON DELETE RESTRICT,
    schedule_form_detail_id BIGINT REFERENCES schedule_form_details(id) ON DELETE RESTRICT,
    source_type VARCHAR(50) NOT NULL,
    source_action VARCHAR(50) NOT NULL DEFAULT 'save',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT chk_repair_remark_loco_source
        CHECK (num_nonnulls(loco_id, temporary_loco_id) <= 1)
);

CREATE INDEX IF NOT EXISTS idx_repair_remarks_date_loco
    ON repair_schedule_remarks (assignment_date DESC, loco_id, temporary_loco_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_repair_remarks_header
    ON repair_schedule_remarks (assign_work_header_id, created_at);
CREATE INDEX IF NOT EXISTS idx_repair_remarks_distribution
    ON repair_schedule_remarks (manpower_distribution_id, created_at);
CREATE INDEX IF NOT EXISTS idx_repair_remarks_form
    ON repair_schedule_remarks (schedule_form_detail_id, created_at);
CREATE OR REPLACE FUNCTION reject_repair_remark_change()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION 'repair_schedule_remarks is append-only; rows cannot be updated or deleted';
END;
$$;

DROP TRIGGER IF EXISTS trg_repair_remarks_no_update ON repair_schedule_remarks;
CREATE TRIGGER trg_repair_remarks_no_update
BEFORE UPDATE ON repair_schedule_remarks
FOR EACH ROW EXECUTE FUNCTION reject_repair_remark_change();

DROP TRIGGER IF EXISTS trg_repair_remarks_no_delete ON repair_schedule_remarks;
CREATE TRIGGER trg_repair_remarks_no_delete
BEFORE DELETE ON repair_schedule_remarks
FOR EACH ROW EXECUTE FUNCTION reject_repair_remark_change();

COMMIT;
