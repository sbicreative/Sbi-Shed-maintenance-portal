-- REVIEW BEFORE APPLYING. Links selected pending repair remarks to a Repairs work assignment.
-- Existing remarks, assignments and form data are not modified or backfilled.
BEGIN;

CREATE TABLE IF NOT EXISTS repair_schedule_remark_assignments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    repair_schedule_remark_id BIGINT NOT NULL
        REFERENCES repair_schedule_remarks(id) ON DELETE RESTRICT,
    assign_work_detail_id BIGINT NOT NULL
        REFERENCES assign_work_details(id) ON DELETE RESTRICT,
    assigned_by BIGINT NOT NULL,
    assigned_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (repair_schedule_remark_id, assign_work_detail_id)
);

CREATE INDEX IF NOT EXISTS idx_repair_remark_assignments_detail
    ON repair_schedule_remark_assignments(assign_work_detail_id, assigned_at);
CREATE INDEX IF NOT EXISTS idx_repair_remark_assignments_remark
    ON repair_schedule_remark_assignments(repair_schedule_remark_id, assigned_at);

COMMIT;
